// Concatenate core/src/*.js into core/dist/hive-core.js: one global, HiveCore.
// The output has no require/import, so it can be pasted into an n8n Code node, and it ends
// with a guarded module.exports so Node tests and the headless benchmark can require() it.
//   node core/build.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
// Dependency order: later files use the globals defined by earlier ones.
const ORDER = ['events.js', 'cbba.js', 'score.js', 'digest.js', 'search.js', 'text-fallback.js', 'actor.js'];
const GUARD = /^if \(typeof module !== 'undefined' && module\.exports\).*$/m;

const params = JSON.parse(read('contracts/params.json'));
const gazetteer = JSON.parse(read('contracts/gazetteer.json')).districts;

const parts = [
  `// GENERATED by core/build.mjs from core/src and contracts/. Do not edit.`,
  `const HIVE_PARAMS = ${JSON.stringify(params)};`,
  `const HIVE_GAZETTEER = ${JSON.stringify(gazetteer)};`,
];
for (const f of ORDER) {
  const p = `core/src/${f}`;
  if (!existsSync(new URL(p, root))) continue;
  parts.push(`// ---- ${f} ----\n${read(p).replace(GUARD, '').trimEnd()}`);
}
parts.push(`HiveCore.Events = HiveEvents; HiveCore.CBBA = HiveCBBA; HiveCore.Score = HiveScore; HiveCore.Digest = HiveDigest; HiveCore.Search = HiveSearch;`);
parts.push(`if (typeof HiveText !== 'undefined') HiveCore.Text = HiveText;`);
parts.push(`try { if (typeof module !== 'undefined' && module.exports) module.exports = HiveCore; } catch (e) {}`);

const out = parts.join('\n\n') + '\n';
if (/\brequire\s*\(/.test(out) || /^\s*import\s/m.test(out)) throw new Error('core must not contain require() or import');
mkdirSync(new URL('core/dist/', root), { recursive: true });
writeFileSync(new URL('core/dist/hive-core.js', root), out);
console.log(`core/dist/hive-core.js: ${(out.length / 1024).toFixed(1)} KB`);
