#!/usr/bin/env node
// Generates docker-compose.yml for HIVE from contracts/params.json.
//
//   node scripts/gen-compose.mjs                                  # all 7 actors
//   node scripts/gen-compose.mjs --actors drone-1,drone-2,team-1,team-2   # dev stack
//   node scripts/gen-compose.mjs --with-probe                     # adds the Phase 0 network probe
//   node scripts/gen-compose.mjs --stdout                         # print instead of writing
//
// Network design (implementation.md D5): each actor gets a private network net-<id> holding only
// its n8n and its store (alias "store"). Shared services (sim, proxy, dashboard, probe) join every
// actor network; hq joins only net-hq with the proxy. Two actors never share a network.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function parseArgs(argv) {
  const opts = { actors: null, withProbe: false, stdout: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--actors') opts.actors = argv[++i].split(',').map((s) => s.trim()).filter(Boolean);
    else if (a.startsWith('--actors=')) opts.actors = a.slice(9).split(',').map((s) => s.trim()).filter(Boolean);
    else if (a === '--with-probe') opts.withProbe = true;
    else if (a === '--stdout') opts.stdout = true;
    else throw new Error(`unknown argument: ${a}`);
  }
  return opts;
}

// hasService(name) → true if services/<name>/Dockerfile exists. Injected for tests.
export function generate(params, { actors = null, withProbe = false, hasService } = {}) {
  const all = [...params.actors.drones, ...params.actors.teams];
  const chosen = actors ?? all;
  for (const a of chosen) if (!all.includes(a)) throw new Error(`unknown actor "${a}" (known: ${all.join(', ')})`);
  if (new Set(chosen).size !== chosen.length) throw new Error('duplicate actor in --actors');
  const role = (a) => (params.actors.drones.includes(a) ? 'drone' : 'team');
  const hostPort = (a) => params.ports.n8n_host_base + all.indexOf(a); // fixed per actor, even in a subset
  const net = (a) => `net-${a}`;
  const vol = (s) => s.replace(/-/g, '_');
  const actorNets = chosen.map(net);
  const L = [];
  const push = (...lines) => L.push(...lines);

  push('# GENERATED by scripts/gen-compose.mjs from contracts/params.json. Do not edit by hand.');
  push(`# Actors: ${chosen.join(', ')}`);
  push('name: hive', '', 'services:');

  chosen.forEach((a, idx) => {
    const peers = chosen.filter((p) => p !== a).join(',');
    // Staggered boot: 7 n8n instances migrating at once overload an 8 GB laptop and never finish
    // starting (measured: load 35+, none ready after 10 min). Each waits for the previous to be READY.
    const prev = idx > 0 ? chosen[idx - 1] : null;
    push(
      `  n8n-${a}:`,
      '    image: n8nio/n8n:${N8N_VERSION:?set N8N_VERSION in .env}',
      '    restart: unless-stopped',
      '    mem_limit: 560m',
      `    ports: ["${hostPort(a)}:${params.ports.n8n}"]`,
      '    environment:',
      '      NODE_OPTIONS: "--max-old-space-size=320"',
      '      N8N_ENCRYPTION_KEY: ${N8N_ENCRYPTION_KEY:?set N8N_ENCRYPTION_KEY in .env}',
      '      N8N_CONCURRENCY_PRODUCTION_LIMIT: "1"',
      '      EXECUTIONS_DATA_SAVE_ON_SUCCESS: ${EXEC_SAVE_SUCCESS:-none}',
      '      EXECUTIONS_DATA_SAVE_ON_ERROR: all',
      '      EXECUTIONS_DATA_PRUNE: "true"',
      '      EXECUTIONS_DATA_MAX_AGE: "12"',
      '      N8N_DIAGNOSTICS_ENABLED: "false"',
      '      N8N_SECURE_COOKIE: "false"',
      '      GENERIC_TIMEZONE: Europe/London',
      '    volumes:',
      `      - n8n_${vol(a)}:/home/node/.n8n`,
      '      - ./n8n/build:/hive/build:ro',
      '      - ./n8n/credentials:/hive/credentials',
      `    networks: [${net(a)}]`,
      '    depends_on:',
      `      store-${a}: { condition: service_healthy }`,
      ...(prev ? [`      n8n-${prev}: { condition: service_healthy }`] : []),
      '    healthcheck:',
      `      test: ["CMD", "node", "-e", "fetch('http://localhost:${params.ports.n8n}/healthz/readiness').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))"]`,
      '      interval: 10s',
      '      timeout: 5s',
      '      start_period: 180s',
      '      retries: 18',
      '',
      `  store-${a}:`,
      '    build: ./services/store',
      '    image: hive-store:dev',
      '    restart: unless-stopped',
      '    mem_limit: 96m',
      '    environment:',
      `      ACTOR_ID: ${a}`,
      `      ROLE: ${role(a)}`,
      '      MODE: ${MODE:-hive}',
      `      PEERS: "${peers}"`,
      '    volumes:',
      `      - store_${vol(a)}:/data`,
      '    networks:',
      `      ${net(a)}: { aliases: [store] }`,
      '    healthcheck:',
      `      test: ["CMD", "node", "-e", "fetch('http://localhost:${params.ports.store}/health').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))"]`,
      '      interval: 5s',
      '      timeout: 3s',
      '      retries: 12',
      '',
    );
  });

  // Shared services: included only once their Dockerfile exists (they arrive in Phase 1+).
  const shared = [
    { name: 'sim', port: params.ports.sim, nets: actorNets, env: ['SEED: "1"', 'TICK_MS: ${TICK_MS:-2000}', `ACTORS: "${chosen.join(',')}"`] },
    { name: 'proxy', port: params.ports.proxy, nets: [...actorNets, 'net-hq'], env: [`ACTORS: "${chosen.join(',')}"`] },
    { name: 'hq', port: params.ports.hq, nets: ['net-hq'], env: ['MODE: ${MODE:-hive}'] },
    { name: 'dashboard', port: params.ports.dashboard, nets: actorNets, env: [`ACTORS: "${chosen.join(',')}"`], publish: true },
  ];
  const included = shared.filter((s) => hasService(s.name));
  for (const s of included) {
    push(
      `  ${s.name}:`,
      `    build: ./services/${s.name}`,
      `    image: hive-${s.name}:dev`,
      '    restart: unless-stopped',
      '    mem_limit: 128m',
      '    environment:',
      `      PORT: "${s.port}"`,
      ...s.env.map((e) => `      ${e}`),
      ...(s.publish ? [`    ports: ["${s.port}:${s.port}"]`] : []),
      `    networks: [${s.nets.join(', ')}]`,
      '',
    );
  }

  if (withProbe) {
    // Phase 0 stand-in for the proxy: a tiny HTTP server on every actor network.
    push(
      '  probe:',
      '    image: node:24-alpine',
      '    mem_limit: 64m',
      '    command: ["node", "-e", "require(\'http\').createServer((q,r)=>r.end(\'probe-ok\')).listen(9000)"]',
      `    networks: [${actorNets.join(', ')}]`,
      '',
    );
  }

  const needsHqNet = included.some((s) => s.nets.includes('net-hq'));
  push('networks:');
  for (const n of actorNets) push(`  ${n}: {}`);
  if (needsHqNet) push('  net-hq: {}');
  push('', 'volumes:');
  for (const a of chosen) push(`  n8n_${vol(a)}: {}`, `  store_${vol(a)}: {}`);
  return { yaml: L.join('\n') + '\n', actors: chosen, included: included.map((s) => s.name) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2));
  const params = JSON.parse(readFileSync(join(ROOT, 'contracts/params.json'), 'utf8'));
  const hasService = (n) => existsSync(join(ROOT, 'services', n, 'Dockerfile'));
  const out = generate(params, { ...opts, hasService });
  if (opts.stdout) process.stdout.write(out.yaml);
  else {
    for (const d of ['n8n/build', 'n8n/credentials']) mkdirSync(join(ROOT, d), { recursive: true });
    writeFileSync(join(ROOT, 'docker-compose.yml'), out.yaml);
    console.log(`docker-compose.yml: ${out.actors.length} actors (${out.actors.join(', ')}); shared services: ${out.included.join(', ') || 'none yet'}${opts.withProbe ? '; + probe' : ''}`);
  }
}
